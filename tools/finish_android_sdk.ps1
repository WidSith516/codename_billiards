# Finish the Android SDK using what is already on disk, instead of re-downloading ~600 MB.
#
# The straight download path stalled: cmdline-tools.zip sat at 0 bytes and never progressed. But a
# previous project on this machine (D:\saint_ruin) already has a working Android SDK whose
# cmdline-tools\bin\sdkmanager.bat is present, and this project's own JDK is already extracted. So the
# missing pieces are only `platforms;android-34` and the accepted licences, and sdkmanager can fetch
# exactly those.
#
# Judged by EXIT CODE, not stderr: these tools write progress and warnings to stderr, which PowerShell
# turns into NativeCommandError records; treating that as failure was a false alarm twice already.
$ErrorActionPreference = "Continue"

$myJdk  = "D:\codename\codename_billiards\godot\.tmp\android\jdk"
$mySdk  = "D:\codename\codename_billiards\godot\.tmp\android\sdk"
$sdkMgr = "D:\saint_ruin\.tmp_android\env\sdk\cmdline-tools\bin\sdkmanager.bat"

foreach ($p in @("$myJdk\bin\java.exe", $sdkMgr)) {
    if (-not (Test-Path $p)) { throw "required tool missing: $p" }
}

$env:JAVA_HOME = $myJdk
$env:ANDROID_HOME = $mySdk
$env:ANDROID_SDK_ROOT = $mySdk
$env:PATH = "$myJdk\bin;" + $env:PATH

New-Item -ItemType Directory -Force -Path $mySdk | Out-Null

# Reuse the precedent's already-downloaded build-tools and platform-tools: copying them is instant and
# avoids depending on the network for the parts that already exist locally.
$preSdk = "D:\saint_ruin\.tmp_android\env\sdk"
foreach ($part in @("build-tools", "platform-tools", "licenses")) {
    $src = Join-Path $preSdk $part
    $dst = Join-Path $mySdk $part
    if ((Test-Path $src) -and -not (Test-Path $dst)) {
        Write-Output "==> copying $part from the existing local SDK"
        Copy-Item $src $dst -Recurse -Force
    }
}

Write-Output "==> accepting licences"
$yes = ("y`n" * 40)
$yes | & $sdkMgr --sdk_root="$mySdk" --licenses 2>&1 | Select-Object -Last 4

Write-Output "==> installing platforms;android-34"
$yes | & $sdkMgr --sdk_root="$mySdk" "platforms;android-34" 2>&1 | Select-Object -Last 8

Write-Output "==> verifying"
$checks = @(
    "$mySdk\platform-tools\adb.exe",
    "$mySdk\build-tools\34.0.0\apksigner.bat",
    "$mySdk\build-tools\34.0.0\zipalign.exe"
)
foreach ($c in $checks) { Write-Output ("  " + $(if (Test-Path $c) { "OK   $c" } else { "MISS $c" })) }
$plat = Get-ChildItem "$mySdk\platforms" -ErrorAction SilentlyContinue
Write-Output ("  platforms: " + $(if ($plat) { ($plat.Name -join ", ") } else { "NONE" }))

$envFile = "D:\codename\codename_billiards\godot\.tmp\android\env.ps1"
@"
# Generated by tools/finish_android_sdk.ps1 -- dot-source this before an Android export.
`$env:JAVA_HOME = "$myJdk"
`$env:ANDROID_HOME = "$mySdk"
`$env:ANDROID_SDK_ROOT = "$mySdk"
`$env:PATH = "$myJdk\bin;$mySdk\platform-tools;" + `$env:PATH
"@ | Set-Content -Path $envFile -Encoding UTF8
Write-Output "wrote $envFile"
Write-Output "DONE"
